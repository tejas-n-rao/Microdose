# Many explicit "Do not do ..." instructuons were based on mistakes made by the agent in earlier stages.
# The latter end of the prompt is dedicated for the explainability for why requests were rejected.
SYSTEM_PROMPT = """You are a ReAct agent, for a drug delivery system.
Respond with one JSON object and no surrounding text:
{"thought": "brief action rationale", "action": "set_mission" | "verify_dispatch_smt" | "propose_alternatives" | "request_compatibility_override" | "ask_user" | "finish", "action_input": {...}}

Extract only specifications explicitly supplied by the user. The required fields
are target_id (A/B/C), dose (positive drug units), carrier_id (X/Y/Z), and layout
(integer geometry ID 0–7). Preference is safety/speed when explicitly stated;
otherwise ask which priority matters more. For every non-null extracted field provide an exact short quote
from the instruction in evidence: {"field_name": "verbatim user phrase"}.
Omit missing fields or set them to null. Never infer a dose, carrier, map or
layout from existing UI defaults. Prefer ask_user when anything is ambiguous.

Interpret priority from meaning, without requiring the words safety or speed:
"avoid damaging healthy tissue even if the trip takes longer" means safety;
"arrive as quickly as possible" means speed. If neither priority is stated, or
both conflict without a clear precedence, ask which matters more. ReAct may
use only Q-learning Safety as its learned controller. It cannot select SARSA. Do not promise that RL always outperforms A*.

Note that Targets are Tumours, and may be used interchangeably in prompt. Targets A/B are type_1, C is type_2. Robot R1 carries reagent X (type_1);
robot R2 carries reagent Y (type_2); robot R3 carries X+Y (either type). Essentially regent X is effective against type_1 tumours, and reagent Y is effective against type_2 tumours.
This is an experimental mapping, and the reagent to tumour mapping is subject to change. The internal carrier IDs are
R1=X, R2=Y and R3=Z; normalize robot names to these IDs in carrier_id, quoting the user's robot phrase as evidence. Reagent names X/Y identify
chemicals, not robots: do not deploy a robot solely from a reagent name.

Terms like R1/R2/R3 mean robots. Layout IDs name vessel geometry. 

First call set_mission with extracted fields and evidence. Then call verify_dispatch_smt with {} (verify_mission is a compatibility alias). This is mandatory: its SMT tool checks reagent/type
matching and selects Q-learning Safety for seen protection-priority missions. Use distance A* for speed, and distance A* for unseen layouts (5/6/7) without a very-high sensor alert.

The unseen override takes precedence over a protection-priority request unless a trusted very-high sensor alert requires Q-learning Safety. A sensor alert also overrides speed requests. 

The user must accept the forced RL plan or cancel before deployment. Never infer acceptance from the original mission priority.

Exactly one tumour is urgent by default, as stated in the runtime urgency
configuration below. This designation does not forbid other treatment or change
speed-based movement priority. A user may explicitly change urgency, e.g.
"Treat C urgently instead of B". Only then set top-level urgent_target="C"
and evidence.urgent_target to that exact user phrase. Otherwise omit it.

Do not infer urgency from a target selection or a request to arrive quickly.
Ask which tumour is urgent if the instruction conflicts, names several urgent tumours, or is ambiguous.

An urgency override never waives dosage, compatibility consent, collisions or unseen A*.

Dosage budgets are supplied at runtime below. Total allocations across carriers
for each tumour must not exceed its required dose. Excess dose requires user changes: propose_alternatives offers reduced allocations for selection.

Reagent mismatch is rejected by default. After verification, call request_compatibility_override {} to ask for a compatible plan or explicit
permission for the listed mismatches. Approval is collected by the UI and bound to the rejected plan; it cannot be invented in action_input or inferred from an
urgency request. Dose, carrier, target, mode or controller changes invalidate it.

Excess dose and collision rules cannot be overridden by compatibility consent.

Ask the user about any additional requested specification that is ambiguous or unsupported (such as a deadline, maximum dose, multi-target mission, reagent
change, or a different RL algorithm). Do not discard such constraints.

Natural-language deployment fixes the horizon at 160 shared timesteps; do not invent a different limit.

For multiple tasks or carriers, call set_mission with {"layout": int,
"execution": "sequential" | "simultaneous",
"evidence": {"layout": "quote"}, "missions": [
{"target_id": "A", "dose": 50, "carrier_id": "X", "preference": "safety",
"evidence": {"target_id": "quote", "dose": "quote", "carrier_id": "quote", "preference": "quote"}}, ...]}.

For a single task, the original top-level fields remain valid. A physical
carrier can have several ordered tasks only when the user uses sequencing language
such as "then" or "after that"; preserve those rows in order and set execution="sequential".

Each carrier can still have only one simultaneous mission. Shared layout must be explicit; flow is assigned by the backend. Extract every requested carrier; never collapse a fleet
request into one mission. Ask about unspecified targets/doses/priorities per carrier. A shared explicit dose/priority may supply evidence to multiple rows.

Every robot has one movement opportunity per shared timestep. Fast refers to distance-A* routing, which any robot can use.
Shared flow is sampled by the backend: 10% very high stochastic, 60% high stochastic, 30% low stochastic.

Do not ask for flow mode or extract a user flow choice. The backend ASSIGNED_SCENARIO observation fixes mode, The user must still supply the vessel layout.
Every robot has a maximum aggregate payload of 60 simulation units, separate from per-target budgets. The loop has at most eight iterations.

After UNSATISFIABLE, reflect on diagnostics and call propose_alternatives {}. While parsing, treat diagnostics.violations as the rejection explanation. 

Tell the user each concrete `explanation` and `repair`; do not expose a raw rule ID as the only reason. 
The UNSAT core is a sufficient subset and may omit other independently violated rules already listed in diagnostics.violations.
Its plans preserve targets, layout, scenario and intent while repairing
carrier allocations or reducing excessive doses; never silently change dosage. Then ask_user to choose a verified plan. 

Never change a requested carrier. Never repeat the same rejected payload; the
loop intercepts duplicates. Only finish after the latest exact plan is verified.

If specifications are missing, ask_user with {"questions": ["..."]}.

If ask_user returns SPECIFICATIONS_PRESENT, the backend has grounded those
fields to verbatim request text. Do not ask them again; call
verify_dispatch_smt with {} on the stored draft.

If SMT rejects compatibility, ask the user to change the carrier or target;
never swap a reagent or tumour, or invent override permission. After a VERIFIED_MISSION observation,
call finish with {"final_answer": "brief mission confirmation"}.
"""



class OpenAIMissionLLM:


    def __init__(self, model: str | None = None, api_key: str | None = None):
        load_project_env()

        try:
            from openai import OpenAI
        except ImportError as exc:
            raise MissionParseError("The openai package is not installed.") from exc

        key = api_key or os.environ.get("OPENAI_API_KEY")
        if not key:
            raise MissionParseError("OPENAI_API_KEY is not set.")

        self.model = model or default_llm_model()
        self.client = OpenAI(api_key=key)


    def step(self, messages: list[dict[str, str]]) -> str:
        # referrs to ReAct Lab/llm_client.py: the same step(messages) wrapper around chat completions.
        response = self.client.chat.completions.create(
            model=self.model,
            messages=[{"role": "system", "content": SYSTEM_PROMPT + f"\nConfigured urgent tumour: {RULES['urgent_tumour']} (the other two are nonurgent). Reagent budgets: {RULES['required_doses']} simulation units."}] + messages,
        )
        content = response.choices[0].message.content
        if not content:
            raise MissionParseError("The LLM returned an empty response.")
        return content



def model_to_dict(model: BaseModel) -> dict[str, Any]:
    if hasattr(model, "model_dump"):
        return model.model_dump()
    return model.dict()



def parse_step(raw):
    # Validate the JSON step before using its action.
    # I follow something similat to Z3Lab's agent.py, as parse_step validates JSON with AgentStep.
    return AgentStep.model_validate(json.loads(raw))



# Z3Lab/agent.py: observation messages serialize tool results to JSON.
# Unused console helper, the UI keeps the complete transcript instead.
def _observation_note(result):
    return 'Observation: ' + json.dumps(result, sort_keys=True)



def _obs_msg(result, sensor_observation=None):


    # Actual dynamics remain simulator state, rather than an leaking unknown data.  
    def public(value):
        if isinstance(value, dict):
            return {key: sensor_observation['predicted_mode'] if key == 'mode' and sensor_observation
                    else public(item) for key, item in value.items()}
        if isinstance(value, list):
            return [public(item) for item in value]
        return value
    return "Observation: " + json.dumps(public(result))



def sample_natural_language_mode(rng=None):
    # Sample one shared scenario, independent of layout and LLM output.
    draw = (rng or random).random()
    probabilities = RULES['natural_language_scenarios']
    if draw < probabilities['very_high']:
        return 'very_high'
    return 'stochastic' if draw < probabilities['very_high'] + probabilities['stochastic'] else 'low'



def run_mission_react_loop(llm, instruction: str, max_iterations: int = MAX_ITERATIONS, compatibility_approvals=None, scenario_mode=None, sensor_observation=None, sensor_approval=None):
    """Same as the react and z3 lab: parse -> validate -> registry call -> observation -> reflect

    NOTE: Logical errors remain observations so ReAct can propose Z3-backed repairs.
    The latest exact draft must have a SAT result before finish is accepted.
    """
    context = MissionContext(instruction, compatibility_approvals, scenario_mode, sensor_observation, sensor_approval)
    # Ground explicit details first so a model error cannot ask for them again.
    if context.explicit:
        grounded = context.set_mission(**context.explicit)
        if grounded.get('status') != 'DRAFT_EXTRACTED':
            context.draft = None
            context.last_result = None
    tools = make_tool_registry(context)
    
    # Borrowed from ReAct Lab/react_loop_lab.py: start the transcript with the request verbatim.
    messages = [{"role": "user", "content": instruction}]
    if compatibility_approvals:
        messages.append({'role': 'user', 'content': _obs_msg({'status': 'USER_COMPATIBILITY_APPROVALS',
            'receipts': compatibility_approvals, 'feedback': 'Backend-recorded user consent; SMT must check exact plan scope.'})})
    if scenario_mode:
        if scenario_mode not in ('low', 'stochastic', 'very_high'):
            raise MissionParseError('Natural-language flow must be low, high, or very high stochastic.')
        messages.append({'role': 'user', 'content': _obs_msg({'status': 'ASSIGNED_SCENARIO',
            'mode': sensor_observation['predicted_mode'] if sensor_observation else scenario_mode, 'feedback': 'Backend-sampled shared flow. Do not ask the user for mode or override it. User chooses layout.'})})
    if sensor_observation:
        messages.append({'role': 'user', 'content': _obs_msg({'status': 'ENVIRONMENT_SENSOR',
            'observation': sensor_observation, 'feedback': 'Trusted sensor prediction, not user-editable. A very-high alert forces Q-learning Safety, even for speed or unseen geometry. Backend requires explicit acceptance before deployment.'})})
    turn_limit = min(max_iterations, MAX_ITERATIONS)

    for _iteration in range(turn_limit):
        raw_response = llm.step(messages)
        messages.append({"role": "assistant", "content": raw_response})

        try:
            step = parse_step(raw_response)
            if step.action not in TOOL_ARG_MODELS:
                raise ValueError("Valid actions: " + ", ".join(TOOL_ARG_MODELS))
           
            # validate tool arguments before dispatch, again from react lab
            validated = TOOL_ARG_MODELS[step.action](**step.action_input)
        except (ValueError, TypeError, ValidationError) as exc:
            messages.append({"role": "user", "content": _obs_msg({"status": "SYNTACTIC_ERROR", "feedback": str(exc)})})
            continue
        if step.action == "finish":
            if context.verified is None:
                messages.append({"role": "user", "content": _obs_msg({"status": "UNVERIFIED_FINISH", "feedback": "Call set_mission and verify_dispatch_smt successfully before finish."})})
                continue
            return context.mission_spec(messages)
        
        # dispatch, then append the tool observation.
        result = tools[step.action](**model_to_dict(validated))
        messages.append({"role": "user", "content": _obs_msg(result, sensor_observation)})
        if result['status'] == 'REQUIRES_SENSOR_ACCEPTANCE':
            raise_sensor_acceptance(context, messages)
        if result['status'] == 'NEEDS_CLARIFICATION':
            if context.last_result and context.last_result['status'] == 'UNSATISFIABLE' and not context.alternatives:
                proposals = context.propose_alternatives()
                messages.append({"role": "user", "content": _obs_msg(proposals, sensor_observation)})
            questions = context.rejection_questions() or result['questions']
            raise MissionClarificationRequired(questions, messages, context.draft, context.alternatives,
                                                context.override_options(), context.last_result)
    
    # Verify the latest draft once more if the model spends its turn budget.
    if context.draft is not None:
        result = context.verify(recheck=True)
        messages.append({'role': 'user', 'content': _obs_msg(result, sensor_observation)})
    if context.last_result and context.last_result['status'] == 'REQUIRES_SENSOR_ACCEPTANCE':
        raise_sensor_acceptance(context, messages)
    if context.last_result and context.last_result['status'] == 'UNSATISFIABLE':
        proposals = context.propose_alternatives()
        messages.append({"role": "user", "content": _obs_msg(proposals, sensor_observation)})
        options = context.override_options()
        questions = context.rejection_questions()
        raise MissionClarificationRequired(questions,
                                          messages, context.draft, context.alternatives, options, context.last_result)
    raise MissionClarificationRequired(
        [f'ReAct reached its {turn_limit}-turn limit without completing admission. '
         'Review or revise the instruction below, then verify again. No new mission was deployed.'],
        messages, context.draft)



def raise_sensor_acceptance(context, messages):
    result = context.last_result
    raise MissionClarificationRequired(
        ['Sensors predict very high stochasticity. A* will not be used. Accept Q-learning Safety for this plan, or cancel deployment.'],
        messages, context.draft, sensor_prompt=dict(payload=context.draft,
            proposal=result, observation=context.sensor_observation))



def parse_mission_instruction(instruction: str, model: str | None = None, max_iterations: int = MAX_ITERATIONS, compatibility_approvals=None, scenario_mode=None, sensor_observation=None, sensor_approval=None):
    if not instruction.strip():
        raise MissionParseError("Instruction is empty.")
    from src.simulation.environment_sensor import observe_environment
    mode = scenario_mode or sample_natural_language_mode()
    observation = sensor_observation or observe_environment(mode)
    return run_mission_react_loop(OpenAIMissionLLM(model=model), instruction, max_iterations,
                                  compatibility_approvals, mode, observation, sensor_approval)
